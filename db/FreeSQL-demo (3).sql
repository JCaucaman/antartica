
CREATE TABLE PAIS (
    ID_PAIS INTEGER PRIMARY KEY NOT NULL,
    PS_NOMBRE_OFICIAL VARCHAR(50) NOT NULL,
    PS_PRESUPUESTO_ANUAL INTEGER NOT NULL,
    PS_ORGANISMO_RESPONASABLE VARCHAR(50) NOT NULL
);

CREATE TABLE BASE_PAIS (
    ID_BASE INTEGER PRIMARY KEY NOT NULL,
    BS_FECHA_INSTALACION VARCHAR(32) NOT NULL,
    BS_UBICACION VARCHAR(32) NOT NULL,
    BS_NOMBRE_BASE VARCHAR(32) NOT NULL,
    BS_FK_PAIS INTEGER REFERENCES PAIS(ID_PAIS)
);

CREATE TABLE SECTOR (
    ID_SECTOR INTEGER NOT NULL,
    SCT_FK_BASE INTEGER NOT NULL REFERENCES BASE_PAIS(ID_BASE),
    SCT_NIVEL_AISLAMIENTO VARCHAR(32) NOT NULL,
    SCT_SUPERFICIE INTEGER NOT NULL,
    SCT_NOMBRE_SECTOR VARCHAR(32) NOT NULL,
    SCT_NIVEL_ACCESO VARCHAR(32) NOT NULL,
    SCT_CONDICIONES_CLI VARCHAR(32) NOT NULL,

    PRIMARY KEY (ID_SECTOR, SCT_FK_BASE)
);

CREATE TABLE PERSONAL(
    ID_PERSONAL INTEGER PRIMARY KEY NOT NULL,
    PER_NOMBRE VARCHAR(32) NOT NULL,
    PER_CIENTIFICO INTEGER NOT NULL,
    PER_TECNICO INTEGER NOT NULL,
    PER_ADMIN INTEGER NOT NULL,
    PER_COORDINADOR INTEGER NOT NULL
);

CREATE TABLE USUARIO(
    N_ACCESO_USER VARCHAR(32) NOT NULL,
    USER_NOMBRE_USUARIO VARCHAR(32) NOT NULL,
    USER_CONSTRASENNA VARCHAR(32) NOT NULL,
    USER_ROL VARCHAR(32) NOT NULL,
    USER_FK_PERSONAL INTEGER REFERENCES PERSONAL(ID_PERSONAL),

    PRIMARY KEY (N_ACCESO_USER, USER_FK_PERSONAL)
);

CREATE TABLE EXPEDICION (
    ID_EXPEDICION INTEGER PRIMARY KEY,
    EXP_FECHA_INICIO VARCHAR(32) NOT NULL,
    EXP_DURAEXPEDIAS INTEGER NOT NULL,
    EXP_CANTMUESTRAEXPE INTEGER NOT NULL,
    EXP_FK_BASE INTEGER REFERENCES BASE_PAIS(ID_BASE),
    EXP_FK_PERSONAL_ACARGO INTEGER REFERENCES PERSONAL(ID_PERSONAL)
);

CREATE TABLE PERSONAL_PARTICIPAR (
    ID_EXPEDICION INTEGER NOT NULL REFERENCES EXPEDICION(ID_EXPEDICION),
    ID_PERSONAL INTEGER NOT NULL REFERENCES PERSONAL(ID_PERSONAL),
    PP_ESTADO VARCHAR(32) NOT NULL,
    PP_FECHA_INCORPORACION VARCHAR(32) NOT NULL,
    PP_FUNCION_DESEMPENNADA VARCHAR(32) NOT NULL,
    PP_OBSERVACIONES VARCHAR(32) NOT NULL,

    PRIMARY KEY (ID_EXPEDICION, ID_PERSONAL)
);

CREATE TABLE MUESTRA(
    ID_MUESTRA INTEGER PRIMARY KEY,
    MST_ESTADO_CONSERVACION VARCHAR(32) NOT NULL,
    MST_DESCRIPCION VARCHAR(32) NOT NULL,
    MST_TIPO_MUESTRA VARCHAR(32) NOT NULL,
    MST_FK_PERSONAL INTEGER REFERENCES PERSONAL(ID_PERSONAL)
);

CREATE TABLE EVALUACION(
    ID_EVALUACION INTEGER NOT NULL,
    ID_EXPEDICION INTEGER NOT NULL REFERENCES EXPEDICION(ID_EXPEDICION),
    EVA_CALIFICCACION INTEGER NOT NULL,
    EVA_FECHA_EVALUACION VARCHAR(32) NOT NULL,
    EVA_FK_PERSONAL INTEGER REFERENCES PERSONAL(ID_PERSONAL),

    PRIMARY KEY (ID_EVALUACION, ID_EXPEDICION)
);

CREATE TABLE REGISTRO_MUESTRA (
    ID_RECOLECION INTEGER NOT NULL,
    ID_EXPEDICION INTEGER NOT NULL REFERENCES EXPEDICION(ID_EXPEDICION),
    RM_FECHA_RECOLECCION VARCHAR(32) NOT NULL,
    RM_FK_PERSONAL_RESPONTABLE INTEGER REFERENCES PERSONAL(ID_PERSONAL),
    RM_FK_BASE INTEGER NOT NULL,
    RM_FK_SECTOR INTEGER NOT NULL,
    RM_FK_MUESTRA INTEGER NOT NULL REFERENCES MUESTRA(ID_MUESTRA),

    PRIMARY KEY (ID_RECOLECION, ID_EXPEDICION),
    FOREIGN KEY (RM_FK_SECTOR, RM_FK_BASE) REFERENCES SECTOR(ID_SECTOR, SCT_FK_BASE),
    FOREIGN KEY (RM_FK_BASE) REFERENCES BASE_PAIS(ID_BASE)
);